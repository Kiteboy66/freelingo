"""Core isiXhosa A1 grammar for a two-week speaking sprint."""

from app.data._types import GrammarExample, GrammarMistake, GrammarTopic


def _topic(
    slug: str,
    title: str,
    category: str,
    summary: str,
    explanation: str,
    structure: str,
    examples: list[tuple[str, str]],
    *,
    rules: list[str] | None = None,
    mistakes: list[tuple[str, str, str]] | None = None,
) -> GrammarTopic:
    return GrammarTopic(
        slug=slug,
        title=title,
        level="A1",
        category=category,
        summary=summary,
        explanation=explanation,
        structure=structure,
        rules=rules or [],
        examples=[GrammarExample(text=text, translation=translation) for text, translation in examples],
        common_mistakes=[
            GrammarMistake(wrong=wrong, correct=correct, note=note)
            for wrong, correct, note in (mistakes or [])
        ],
    )


